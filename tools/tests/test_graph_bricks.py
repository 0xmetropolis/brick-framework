"""Tests for tools/graph_bricks.py: bricks, source ports, joints and computed shapes as Mermaid."""

from __future__ import annotations

from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

from tools import graph_bricks

ROOT = Path(__file__).resolve().parents[2]


class GraphTests(unittest.TestCase):
    def setUp(self) -> None:
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = Path(tmp.name)
        (self.root / "bricks").mkdir()

    def brick(self, name: str, ports: str, extra: str = "", main: bool = False) -> Path:
        path = self.root / "bricks" / name
        path.mkdir()
        (path / "contract.py").write_text(f"PORTS = {ports}\n{extra}", encoding="utf-8")
        if main:
            (path / "__main__.py").write_text("", encoding="utf-8")
        return path

    def graph(self) -> str:
        bricks = {
            path.name: graph_bricks.read_contract(path)
            for path in sorted((self.root / "bricks").iterdir())
        }
        return graph_bricks.render(bricks)

    def test_a_source_is_a_cylinder_with_its_epoch_and_an_arrow_from_its_brick(self) -> None:
        self.brick("pricing", '{"rates": {"kind": "source", "epoch": 2, "label": {"api": "v2"}}}')
        text = self.graph()
        self.assertIn('pricing__rates[("rates<br/>epoch 2")]', text)
        self.assertIn("pricing --> pricing__rates", text)

    def test_a_followable_source_says_so(self) -> None:
        self.brick("assistant", '{"xai": {"kind": "source", "epoch": 1, "followable": True}}')
        self.assertIn('assistant__xai[("xai<br/>epoch 1<br/>followable")]', self.graph())

    def test_joints_are_drawn_by_policy_and_a_following_joint_is_thick(self) -> None:
        self.brick("assistant", '{"xai": {"kind": "source", "epoch": 1, "followable": True}}')
        self.brick("pricing", "{}")
        self.brick(
            "chat",
            '{"assistant": {"kind": "joint", "policy": "orchestrated", "pin": 1, "follow": ("xai",)}}',
            main=True,
        )
        self.brick("checkout", '{"pricing": {"kind": "joint", "policy": "eventual", "pin": 1}, "assistant": {"kind": "joint", "policy": "orchestrated", "pin": 1}}')
        text = self.graph()
        self.assertIn('chat ==>|"orchestrated, follows xai"| assistant', text)
        self.assertIn("checkout -.->|eventual| pricing", text)
        self.assertIn("checkout -->|orchestrated| assistant", text)

    def test_entry_and_sealed_bricks_carry_their_shape_and_open_ones_do_not(self) -> None:
        self.brick("chat", '{"x": {"kind": "source", "epoch": 1}}', main=True)
        self.brick("planner", "{}")
        self.brick("ordinary", '{"x": {"kind": "source", "epoch": 1}}')
        text = self.graph()
        self.assertIn('chat["chat<br/>entry"]', text)
        self.assertIn('planner["planner<br/>sealed"]', text)
        self.assertIn('ordinary["ordinary"]', text)

    def test_owned_state_and_declared_nondeterminism_stay_in_the_label(self) -> None:
        self.brick("load", "{}", 'OWNED_STATE = ("database:orders",)\nDETERMINISTIC = False\n')
        text = self.graph()
        self.assertIn("load<br/>sealed<br/>database:orders<br/>nondeterministic", text)

    def test_bricks_nothing_depends_on_are_thick_only_when_some_are_depended_on(self) -> None:
        self.brick("lib", "{}")
        self.brick("app", '{"lib": {"kind": "joint", "policy": "eventual", "pin": 1}}')
        text = self.graph()
        self.assertIn("class app topLevel", text)
        alone = tempfile.TemporaryDirectory()
        self.addCleanup(alone.cleanup)
        (Path(alone.name) / "bricks/one").mkdir(parents=True)
        (Path(alone.name) / "bricks/one/contract.py").write_text("PORTS = {}\n", encoding="utf-8")
        self.assertNotIn("topLevel", graph_bricks.render({"one": graph_bricks.read_contract(Path(alone.name) / "bricks/one")}))

    def test_a_malformed_manifest_draws_a_bare_open_brick(self) -> None:
        self.brick("odd", "make_ports()")
        self.assertIn('odd["odd"]', self.graph())

    def test_the_committed_template_draws_its_one_source(self) -> None:
        done = subprocess.run([sys.executable, str(ROOT / "tools/graph_bricks.py")], capture_output=True, text=True, check=False)
        self.assertEqual(done.returncode, 0, done.stderr)
        self.assertIn('example_brick__example_source[("example_source<br/>epoch 1")]', done.stdout)
        self.assertTrue(done.stdout.startswith("%% Generated by tools/graph_bricks.py"))

    def test_an_empty_or_missing_bricks_folder_is_an_error(self) -> None:
        for root in (self.root,):
            done = subprocess.run([sys.executable, str(ROOT / "tools/graph_bricks.py"), "--root", str(root)], capture_output=True, text=True, check=False)
            self.assertEqual(done.returncode, 1)
            self.assertIn("no bricks to graph", done.stderr)
        done = subprocess.run([sys.executable, str(ROOT / "tools/graph_bricks.py"), "--root", str(self.root / "nowhere")], capture_output=True, text=True, check=False)
        self.assertIn("bricks directory is missing", done.stderr)


if __name__ == "__main__":
    unittest.main()
