#!/usr/bin/env python3
"""Draw a brick project from its contracts, deterministically, using only the standard library.

    python3 tools/graph_bricks.py [--root PROJECT] [--format mermaid|dot] [--output FILE]

The diagram is read statically: only each brick's ``contract.py`` (parsed, never imported)
and the names of its files are looked at. Nothing runs, nothing touches the network, nothing
carries a timestamp or a path of this machine, and bricks, ports and edges are sorted, so the
same project always gives the same bytes.

Every brick is a box labelled with its computed shape (``sealed``, ``entry`` or ``open``);
every source port is a cylinder with its epoch, label and whether it is followable; a joint
is an arrow to the sibling labelled with its policy and pin (dashed for ``eventual``); a
follow is a thick arrow from the brick to each source its joint follows.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass, field
import json
from pathlib import Path
import sys
from typing import Any

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from brick_contract import brick_shape, contract_value  # type: ignore[no-redef]
    from mermaid import escape as mermaid_escape, identifier  # type: ignore[no-redef]
else:
    from .brick_contract import brick_shape, contract_value
    from .mermaid import escape as mermaid_escape, identifier

HEADER = (
    "Generated by tools/graph_bricks.py from contract.py files only. "
    "Box: a brick and its computed shape. Cylinder: a source port. "
    "Dashed arrow: eventual joint. Solid arrow: orchestrated joint. Thick arrow: a followed source."
)


@dataclass
class Brick:
    """What the graph draws of one brick."""

    shape: str = "open"
    sources: dict[str, dict[str, Any]] = field(default_factory=dict)
    joints: dict[str, dict[str, Any]] = field(default_factory=dict)
    owned_state: tuple[str, ...] = ()
    deterministic: "bool | None" = None


def read_contract(brick: Path) -> Brick:
    """Read one brick's ports, owned state and determinism, and compute its shape."""
    ports = contract_value(brick, "PORTS")
    ports = ports if isinstance(ports, dict) else {}
    owned_state = contract_value(brick, "OWNED_STATE")
    deterministic = contract_value(brick, "DETERMINISTIC")
    return Brick(
        shape=brick_shape(brick),
        sources={
            name: port for name, port in ports.items()
            if isinstance(name, str) and isinstance(port, dict) and port.get("kind") == "source"
        },
        joints={
            name: port for name, port in ports.items()
            if isinstance(name, str) and isinstance(port, dict) and port.get("kind") == "joint"
            and port.get("policy") in {"eventual", "orchestrated"}
        },
        owned_state=tuple(sorted(item for item in owned_state if isinstance(item, str) and item))
        if isinstance(owned_state, (tuple, list)) else (),
        deterministic=deterministic if isinstance(deterministic, bool) else None,
    )


def read_project(root: Path) -> dict[str, Brick]:
    """Every brick under ``<root>/bricks``, by name."""
    return {
        path.name: read_contract(path)
        for path in sorted((root / "bricks").iterdir())
        if path.is_dir() and not path.name.startswith((".", "__"))
    }


def label_text(label: Any) -> str:
    """A port's label as sorted ``key=value`` pairs."""
    if not isinstance(label, dict) or not label:
        return ""
    return ", ".join(
        f"{key}={value if isinstance(value, str) else json.dumps(value, sort_keys=True)}"
        for key, value in sorted(label.items(), key=lambda item: str(item[0]))
    )


def brick_lines(name: str, brick: Brick) -> list[str]:
    """The lines of a brick's label: name, shape, owned state, a declared nondeterminism."""
    lines = [name, brick.shape, *brick.owned_state]
    if brick.deterministic is False:
        lines.append("nondeterministic")
    return lines


def source_lines(name: str, port: dict[str, Any]) -> list[str]:
    """The lines of a source's label: name, epoch, label, followable."""
    lines = [name, f"epoch {port.get('epoch', '?')}"]
    label = label_text(port.get("label"))
    if label:
        lines.append(f"label {label}")
    if port.get("followable"):
        lines.append("followable")
    return lines


def joint_text(port: dict[str, Any]) -> str:
    return f"{port['policy']}, pin {port.get('pin', '?')}"


def edges(bricks: dict[str, Brick]) -> list[tuple[str, tuple[str, ...], tuple[str, ...], str]]:
    """Every edge as ``(kind, from, to, label)``, sorted.

    ``from`` and ``to`` are ``(brick,)`` or ``(brick, source)``. Kinds: ``source`` (a brick owns a
    source), ``eventual`` and ``orchestrated`` (a joint), ``follow`` (a joint's followed source).
    """
    found: list[tuple[str, tuple[str, ...], tuple[str, ...], str]] = []
    for name in sorted(bricks):
        brick = bricks[name]
        for source in sorted(brick.sources):
            found.append(("source", (name,), (name, source), ""))
        for joint, port in sorted(brick.joints.items()):
            found.append((port["policy"], (name,), (joint,), joint_text(port)))
            callee = bricks.get(joint)
            for followed in sorted(item for item in port.get("follow") or () if isinstance(item, str)):
                if callee is not None and followed in callee.sources:
                    found.append(("follow", (name,), (joint, followed), "follows"))
    return found


def render(bricks: dict[str, Brick]) -> str:
    """Render the project as a Mermaid flowchart."""
    taken: set[str] = set()
    brick_ids = {name: identifier("b_", name, taken) for name in sorted(bricks)}
    source_ids = {
        (name, source): identifier("s_", f"{name}__{source}", taken)
        for name in sorted(bricks) for source in sorted(bricks[name].sources)
    }
    ghosts = sorted({joint for brick in bricks.values() for joint in brick.joints if joint not in bricks})
    for ghost in ghosts:
        brick_ids[ghost] = identifier("b_", ghost, taken)

    def node(target: tuple[str, ...]) -> str:
        return source_ids[target] if len(target) == 2 else brick_ids[target[0]]

    lines = [f"%% {HEADER}", "flowchart TD"]
    for name in sorted(bricks):
        label = "<br/>".join(mermaid_escape(line) for line in brick_lines(name, bricks[name]))
        lines.append(f'    {brick_ids[name]}["{label}"]')
    for ghost in ghosts:
        lines.append(f'    {brick_ids[ghost]}["{mermaid_escape(ghost)}<br/>missing"]')
    for name in sorted(bricks):
        for source, port in sorted(bricks[name].sources.items()):
            label = "<br/>".join(mermaid_escape(line) for line in source_lines(source, port))
            lines.append(f'    {source_ids[(name, source)]}[("{label}")]')

    drawn = []
    for kind, start, end, label in edges(bricks):
        text = f'|"{mermaid_escape(label)}"|' if label else ""
        arrow = {"source": "-->", "eventual": "-.->", "orchestrated": "-->", "follow": "==>"}[kind]
        drawn.append(f"    {node(start)} {arrow}{text} {node(end)}")
    if drawn:
        lines.append("")
        lines.extend(drawn)

    depended_on = {joint for brick in bricks.values() for joint in brick.joints if joint in bricks}
    top_level = [name for name in sorted(bricks) if name not in depended_on]
    if top_level and len(top_level) != len(bricks):
        lines.append("")
        lines.append("    classDef topLevel stroke-width:3px")
        lines.append(f"    class {','.join(brick_ids[name] for name in top_level)} topLevel")
    return "\n".join(lines) + "\n"


def dot_text(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "")


def render_dot(bricks: dict[str, Brick]) -> str:
    """Render the same graph as Graphviz DOT."""
    ghosts = sorted({joint for brick in bricks.values() for joint in brick.joints if joint not in bricks})

    def node(target: tuple[str, ...]) -> str:
        return f'"source:{dot_text(target[0])}:{dot_text(target[1])}"' if len(target) == 2 else f'"brick:{dot_text(target[0])}"'

    lines = [f"// {HEADER}", "digraph bricks {", "  rankdir=TB;", "  node [fontname=Helvetica];"]
    for name in sorted(bricks):
        label = "\\n".join(dot_text(line) for line in brick_lines(name, bricks[name]))
        lines.append(f'  {node((name,))} [shape=box, label="{label}"];')
    for ghost in ghosts:
        lines.append(f'  {node((ghost,))} [shape=box, style=dashed, label="{dot_text(ghost)}\\nmissing"];')
    for name in sorted(bricks):
        for source, port in sorted(bricks[name].sources.items()):
            label = "\\n".join(dot_text(line) for line in source_lines(source, port))
            lines.append(f'  {node((name, source))} [shape=cylinder, label="{label}"];')
    for kind, start, end, label in edges(bricks):
        style = {"source": "", "orchestrated": "", "eventual": "style=dashed", "follow": "style=bold"}[kind]
        attributes = ", ".join(part for part in (f'label="{dot_text(label)}"' if label else "", style) if part)
        lines.append(f"  {node(start)} -> {node(end)}" + (f" [{attributes}]" if attributes else "") + ";")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1], help="the project (default: this repository)")
    parser.add_argument("--format", choices=("mermaid", "dot"), default="mermaid")
    parser.add_argument("--output", type=Path, help="write the diagram to this file instead of stdout")
    args = parser.parse_args(argv)
    root = args.root.resolve()

    if not (root / "bricks").is_dir():
        print(f"{root / 'bricks'}: bricks directory is missing", file=sys.stderr)
        return 1
    bricks = read_project(root)
    if not bricks:
        print(f"{root / 'bricks'}: no bricks to graph", file=sys.stderr)
        return 1
    text = (render_dot if args.format == "dot" else render)(bricks)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(text.encode("utf-8"))
    else:
        sys.stdout.buffer.write(text.encode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
